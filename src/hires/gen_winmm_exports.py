r"""Generate winmm_exports.h and winmm.def from `dumpbin /exports` of the real 32-bit winmm.

Usage (from a VS developer prompt, 32-bit not required for dumpbin):
    dumpbin /exports C:\Windows\SysWOW64\winmm.dll > winmm_dump.txt
    python -I gen_winmm_exports.py winmm_dump.txt

Every export (named or ordinal-only) gets a naked stub `jmp [g_proc[i]]`; winmm.c resolves
g_proc from the real DLL in DllMain. The .def keeps the original names and ordinals.
"""
import re
import sys
from pathlib import Path

if len(sys.argv) != 2:
    sys.exit(__doc__)

here = Path(__file__).resolve().parent
text = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")

exports = []  # (ordinal, name or None)
in_table = False
for line in text.splitlines():
    if re.match(r"\s*ordinal\s+hint\s+RVA\s+name", line):
        in_table = True
        continue
    if not in_table:
        continue
    if line.strip().startswith("Summary"):
        break
    m = re.match(r"\s*(\d+)\s+(?:[0-9A-Fa-f]+\s+)?([0-9A-Fa-f]{8})\s+(\S+)", line)
    if not m:
        continue
    if "(forwarded to" in line:
        sys.exit("forwarded export found - handle it explicitly: " + line)
    ordinal, name = int(m.group(1)), m.group(3)
    exports.append((ordinal, None if name == "[NONAME]" else name))

if not exports:
    sys.exit("no exports parsed")
exports.sort()
n = len(exports)
named = sum(1 for _, nm in exports if nm)

h = ["/* GENERATED by gen_winmm_exports.py from dumpbin /exports of SysWOW64 winmm.dll - do not edit. */",
     f"#define WINMM_EXPORT_COUNT {n}",
     "static const struct { const char *name; unsigned short ord; } g_exp[WINMM_EXPORT_COUNT] = {"]
for o, nm in exports:
    h.append(f'    {{ {("\"" + nm + "\"") if nm else "0"}, {o} }},')
h.append("};")
h.append("static FARPROC g_proc[WINMM_EXPORT_COUNT];")
h.append("")
for i in range(n):
    h.append(f"__declspec(naked) void stub_{i}(void) {{ __asm jmp dword ptr [g_proc + {i * 4}] }}")
h.append("")
(here / "winmm_exports.h").write_text("\n".join(h) + "\n", encoding="ascii", newline="\n")

d = ["LIBRARY winmm", "EXPORTS"]
for i, (o, nm) in enumerate(exports):
    if nm:
        d.append(f"    {nm}=stub_{i} @{o}")
    else:
        d.append(f"    Ordinal{o}=stub_{i} @{o} NONAME")
(here / "winmm.def").write_text("\n".join(d) + "\n", encoding="ascii", newline="\n")
print(f"{n} exports ({named} named, {n - named} ordinal-only)")
